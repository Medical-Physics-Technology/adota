"""The ``dataset_overview`` stage: what the test split holds (metadata, HU, energy, spots, gantry).

Writes only new files under ``<run>/analysis/dataset_overview/``. Every table is written
to CSV first and the figures are drawn from the CSVs read back, so a number on a figure
can always be traced to a file beside it.

Pieces: :mod:`src.engine_drivers.dataset_overview` (per-beamlet metadata and the per-site
summary), :mod:`src.engine_drivers.hu_histogram` (HU of the model-grid crops) and
:mod:`src.figures.dataset_overview` (the figures).
"""
from __future__ import annotations

import logging
from pathlib import Path
from typing import List, Mapping, Optional

import numpy as np
import pandas as pd

logger = logging.getLogger(__name__)

__all__ = ["gantry_sectors", "spot_cells", "run_dataset_overview", "overview_summary"]

SITES = ("thoracic", "abdominal", "pelvic")
CLASS_TEXT = {"below_-500": "below -500 HU", "-500_to_300": "-500 to 300 HU", "above_300": "above 300 HU"}


def gantry_sectors(metadata: pd.DataFrame, bin_deg: float = 15.0) -> pd.DataFrame:
    """Beamlets per gantry sector and site (``site, gantry_bin_low_deg, beamlets``); empty sectors kept."""
    edges = np.arange(0.0, 360.0 + bin_deg, bin_deg)
    rows = []
    for site in SITES:
        part = metadata.loc[metadata["site"] == site, "gantry_deg"].to_numpy()
        counts, _ = np.histogram(np.mod(part, 360.0), bins=edges)
        rows += [{"site": site, "gantry_bin_low_deg": lo, "beamlets": int(c)} for lo, c in zip(edges[:-1], counts)]
    return pd.DataFrame(rows)


def spot_cells(metadata: pd.DataFrame) -> pd.DataFrame:
    """Beamlets per occupied spot lattice position and site (``site, spot_x_mm, spot_y_mm, beamlets``)."""
    frame = metadata.assign(spot_x_mm=metadata["spot_x_mm"].round(6), spot_y_mm=metadata["spot_y_mm"].round(6))
    cells = frame.groupby(["site", "spot_x_mm", "spot_y_mm"]).size().rename("beamlets").reset_index()
    cells["site"] = pd.Categorical(cells["site"], SITES, ordered=True)
    return cells.sort_values(["site", "spot_x_mm", "spot_y_mm"]).reset_index(drop=True)


def _fmt(value: float, digits: int = 1) -> str:
    return f"{value:.{digits}f}"


def _high_hu_lines(hist: pd.DataFrame, threshold: float = 2900.0) -> List[str]:
    """Voxels at or above ``threshold`` HU per site and the fullest bin there (scanner ceilings, metal)."""
    lines = []
    for site in SITES:
        part = hist[hist["site"] == site]
        high = part[part["bin_low_hu"] >= threshold]
        if part.empty or high["count"].sum() == 0:
            continue
        top = high.loc[high["count"].idxmax()]
        lines.append(f"{site} {int(high['count'].sum())} voxels "
                     f"({100.0 * high['count'].sum() / part['count'].sum():.3f}%), most in the bin from "
                     f"{top['bin_low_hu']:.0f} HU ({int(top['count'])})")
    return lines


def overview_summary(summary: pd.DataFrame, classes: pd.DataFrame, clipping: pd.DataFrame,
                     lattice: Mapping[str, int], hist: Optional[pd.DataFrame] = None) -> List[str]:
    """``summary.md`` lines: one table per site, then what the numbers mean and what is missing."""
    lines = ["# Test split of the beamlet pool: data used", "",
             "Run `engine_error_drivers_20261125_153857`, split `v1_apollo_1e6_test.h5` (pool store "
             "`/scratch/mstryja/adota_pool/v1_apollo_1e6`). Generated by the `dataset_overview` stage; every "
             "number below is in a CSV in this folder.", ""]
    total = summary[["patients", "fields", "beamlets", "in_analysis"]].sum()
    lines += [f"In total {int(total['patients'])} patients, {int(total['fields'])} fields and "
              f"{int(total['beamlets'])} beamlets; {int(total['in_analysis'])} have the analytic peak inside the "
              "crop and enter the error analyses.", ""]
    for row in summary.itertuples(index=False):
        part = classes[classes["site"] == row.site].set_index("hu_class")
        lines += [f"## {row.site}", "", "| quantity | value |", "|---|---|",
                  f"| patients / fields / beamlets | {row.patients} / {row.fields} / {row.beamlets} |",
                  f"| beamlets in the error analyses | {row.in_analysis} |",
                  f"| beamlets per patient (min / median / max) | {row.beamlets_per_patient_min} / "
                  f"{_fmt(row.beamlets_per_patient_median)} / {row.beamlets_per_patient_max} |",
                  f"| energy, MeV (min / median / max) | {_fmt(row.energy_min_mev)} / "
                  f"{_fmt(row.energy_median_mev)} / {_fmt(row.energy_max_mev)} |",
                  f"| spot X range, mm | {_fmt(row.spot_x_min_mm)} to {_fmt(row.spot_x_max_mm)} |",
                  f"| spot Y range, mm | {_fmt(row.spot_y_min_mm)} to {_fmt(row.spot_y_max_mm)} |"]
        for key, text in CLASS_TEXT.items():
            lines.append(f"| share of voxels {text} | {100.0 * float(part.loc[key, 'share']):.1f}% |")
        lines.append("")
    n_low, n_high = int(clipping["n_clipped_low"].sum()), int(clipping["n_clipped_high"].sum())
    lines += [
        "## How to read these numbers", "",
        "- **Site** comes from the patient ID prefix (LUNG1 and Lung_Dx thoracic, StageII-Colorectal-CT "
        "abdominal, Prostate-AEC pelvic) and agrees with the pool's stored anatomy for every beamlet.",
        "- **Field** = one patient and one gantry angle (the pool plan's `field_dir`). The gantry angle is the "
        "random angle around the patient; Monte Carlo ran every field at 90 degrees on the CT rotated to match.",
        "- **Couch** is not stored. `couch_deg` is 0 for every beamlet: the MCsquare plan writer's default "
        "patient support angle, which the pool never changes.",
        "- **Spot weight / MU** does not exist for this data: each beamlet is its own Monte Carlo run with 1e6 "
        "primaries, not a spot of a treatment plan. The column and the weighted spot figure are left out.",
        f"- **Spot positions** lie on a lattice of {lattice['x']} x {lattice['y']} steering positions in the "
        "isocentre plane (X lateral, in the gantry rotation plane; Y along the patient axis). The spot figure "
        "has one cell per lattice position, not 5 mm bins, which would leave empty stripes.",
        "- **HU** are those of the crops as the model sees them: 2 mm voxels, each the average of 2 x 2 x 2 "
        "stored 1 mm voxels, converted back from the export's normalisation and rounded to 1/8 HU. A voxel is "
        "counted once per beamlet, so voxels shared by overlapping crops of one field count more than once.",
        "- **Padding:** none of the 7552 crops is padded. Every lateral window lies inside its rotated CT grid "
        "and every grid is at least 334 voxels deep against a 320-voxel crop; a scan of all stored 1 mm crops "
        "found no padded edge plane. The corners added when the CT is rotated to the beam are filled with the "
        "CT's own minimum (air); they lie in front of the patient and stay in the full histogram. The body "
        "histogram (above -500 HU) is unaffected.",
        f"- **Clipping:** {n_low} voxels below -1024 HU and {n_high} above 3071 HU were clipped into the end "
        "bins. Bins are 10 HU wide from -1024; the last bin is partial (3066 to 3071 HU).",
        "- **HU classes** are counted from the voxel values, not from the bins: below -500 means HU < -500, "
        "the middle class -500 <= HU <= 300, above 300 means HU > 300. The body histogram holds HU > -500, "
        "so its total is the two upper classes minus the few voxels at exactly -500 HU.",
        ""]
    high = _high_hu_lines(hist) if hist is not None else []
    if high:
        lines[-1:-1] = ["- **Pile-ups near the top of the HU range** (at or above 2900 HU): " + "; ".join(high)
                        + ". These look like scanner HU ceilings or metal; the cause has not been checked."]
    return lines


def run_dataset_overview(cfg: Mapping, run: Path) -> List[str]:
    """The stage. Returns the ``summary.md`` lines (the caller writes them and the provenance)."""
    from src.engine_drivers import dataset_overview as dov
    from src.engine_drivers import hu_histogram as huh
    from src.figures import dataset_overview as fig

    ocfg = cfg.get("dataset_overview", {})
    formats = tuple(ocfg.get("formats", ["png", "pdf"]))
    bin_deg = float(ocfg.get("gantry_bin_deg", 15.0))
    out = run / "analysis" / "dataset_overview"
    out.mkdir(parents=True, exist_ok=True)
    dataset = Path(cfg["dataset_path"])
    index_csv = dataset.with_name(dataset.stem + "_index.csv")

    metadata = dov.beamlet_metadata(index_csv, Path(ocfg["plan_csv"]), Path(cfg["analysis"]["features_csv"]))
    n_join = dov.check_join(metadata, run / "tables" / "errors_adota.csv")
    metadata.to_csv(out / "beamlet_metadata.csv", index=False)
    dov.site_summary(metadata).to_csv(out / "site_summary.csv", index=False)
    gantry_sectors(metadata, bin_deg).to_csv(out / "gantry_sectors.csv", index=False)
    spot_cells(metadata).to_csv(out / "spot_cells.csv", index=False)
    logger.info("beamlet_metadata.csv: %d beamlets, join to errors_adota.csv %d rows", len(metadata), n_join)

    per_site = huh.accumulate_hu(dataset, dict(zip(metadata["sample_id"], metadata["site"])))
    huh.histogram_frame(per_site).to_csv(out / "hu_histogram_by_site.csv", index=False)
    huh.histogram_frame(per_site, body=True).to_csv(out / "hu_histogram_by_site_body.csv", index=False)
    huh.class_frame(per_site).to_csv(out / "hu_classes_by_site.csv", index=False)
    huh.clipping_frame(per_site).to_csv(out / "hu_clipping.csv", index=False)

    # Figures from the CSVs read back, never from the in-memory frames.
    read = {name: pd.read_csv(out / f"{name}.csv", dtype={"sample_id": str}) for name in (
        "beamlet_metadata", "site_summary", "gantry_sectors", "spot_cells", "hu_histogram_by_site",
        "hu_histogram_by_site_body", "hu_classes_by_site", "hu_clipping")}
    fig.site_hu_histograms_figure(read["hu_histogram_by_site"], title="HU of the CT crops per site",
                                  figure_path=out / "hu_histograms", formats=formats)
    fig.site_hu_histograms_figure(read["hu_histogram_by_site_body"],
                                  title="HU of the CT crops per site, voxels above -500 HU",
                                  figure_path=out / "hu_histograms_body", formats=formats)
    fig.energy_by_site_figure(read["beamlet_metadata"], read["site_summary"], title="Beam energy per site",
                              figure_path=out / "energy_by_site", formats=formats)
    fig.spot_positions_figure(read["spot_cells"], title="Spot positions in the isocentre plane per site",
                              figure_path=out / "spot_positions", formats=formats)
    fig.gantry_polar_figure(read["gantry_sectors"], title="Gantry angles per site (beamlets per 15 degree sector)",
                            figure_path=out / "gantry_polar_beamlets", bin_deg=bin_deg, formats=formats)
    lattice = {"x": int(read["beamlet_metadata"]["spot_x_mm"].round(6).nunique()),
               "y": int(read["beamlet_metadata"]["spot_y_mm"].round(6).nunique())}
    return overview_summary(read["site_summary"], read["hu_classes_by_site"], read["hu_clipping"], lattice,
                            read["hu_histogram_by_site"])
